const BY_KEY = new Map(TASK_ICON_GROUPS.flatMap((g) => g.icons).map((i) => [i.key, i]));

export const isTaskIcon = (key: string) => BY_KEY.has(key);
export const taskIconLabel = (key: string | null | undefined) => (key ? (BY_KEY.get(key)?.label ?? null) : null);

/** Icône d'un type de tâche ; rien si la clé est vide ou inconnue. */
export function TaskIcon({ icon, size = 20, className }: { icon: string | null | undefined; size?: number; className?: string }) {
  const def = icon ? BY_KEY.get(icon) : undefined;
  if (!def) return null;
  const { Icon } = def;
  return <Icon size={size} className={className} aria-hidden strokeWidth={1.75} />;
}
